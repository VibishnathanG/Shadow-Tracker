export interface DietMeal {
  mealType: 'breakfast' | 'snack_morning' | 'lunch' | 'snack_evening' | 'dinner';
  name: string;
  items: string[];
  portion: string;
  calories: number;
  protein: number;
  carbs: number;
  fats: number;
  icon: string;
  tips?: string;
}

export interface DietDay {
  dayName: string; // e.g. 'Monday'
  focus: string;
  totalCalories: number;
  totalProtein: number;
  totalCarbs: number;
  totalFats: number;
  meals: DietMeal[];
}

export interface WeeklyDietPlan {
  id: string;
  name: string;
  tagline: string;
  locality: 'tamilnadu' | 'telugu' | 'kannada' | 'south_general' | 'north' | 'western' | 'custom';
  localityLabel: string;
  targetWeightLossRate: string; // e.g. '0.5 kg / week'
  weeklyLossKg: number;        // e.g. 0.5
  avgDailyCalories: number;
  avgDailyProtein: number;
  avgDailyCarbs: number;
  avgDailyFats: number;
  dietType: 'Non-Veg' | 'Veg' | 'Eggitarian' | 'Vegan' | 'Keto' | 'Millets';
  suitableForSex?: 'all' | 'male' | 'female';
  suitableAgeRange?: string;
  icon: string;
  colorClass: string;
  borderClass: string;
  isCustom?: boolean;
  days: DietDay[];
}

export const STORAGE_CUSTOM_DIETS_KEY = 'shadow_custom_diet_plans_v1';

export function getCustomDietPlans(): WeeklyDietPlan[] {
  if (typeof window === 'undefined') return [];
  try {
    const raw = localStorage.getItem(STORAGE_CUSTOM_DIETS_KEY);
    if (raw) return JSON.parse(raw);
  } catch (e) {
    console.error('Error reading custom diet plans:', e);
  }
  return [];
}

export function saveCustomDietPlan(plan: WeeklyDietPlan): WeeklyDietPlan[] {
  if (typeof window === 'undefined') return [];
  try {
    const existing = getCustomDietPlans();
    const filtered = existing.filter(p => p.id !== plan.id);
    const updated = [plan, ...filtered];
    localStorage.setItem(STORAGE_CUSTOM_DIETS_KEY, JSON.stringify(updated));
    return updated;
  } catch (e) {
    console.error('Error saving custom diet plan:', e);
    return [];
  }
}

export function deleteCustomDietPlan(planId: string): WeeklyDietPlan[] {
  if (typeof window === 'undefined') return [];
  try {
    const existing = getCustomDietPlans();
    const updated = existing.filter(p => p.id !== planId);
    localStorage.setItem(STORAGE_CUSTOM_DIETS_KEY, JSON.stringify(updated));
    return updated;
  } catch (e) {
    console.error('Error deleting custom diet plan:', e);
    return [];
  }
}

// Helper to generate a 7-day variation based on base meals
function make7DayPlan(
  planFocus: string,
  baseCalories: number,
  basePro: number,
  baseCarb: number,
  baseFat: number,
  mealTemplates: (dayIdx: number) => DietMeal[]
): DietDay[] {
  const dayNames = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
  const dayThemes = [
    'Kickoff & Lean Loading',
    'High Fiber & Gut Reset',
    'Midweek Metabolic Boost',
    'Plant & Greens Focus',
    'Peak Protein Velocity',
    'Millets & Functional Carbs',
    'Recovery & Light Detox',
  ];

  return dayNames.map((name, idx) => {
    const meals = mealTemplates(idx);
    const totalCalories = meals.reduce((s, m) => s + m.calories, 0);
    const totalProtein = Math.round(meals.reduce((s, m) => s + m.protein, 0) * 10) / 10;
    const totalCarbs = Math.round(meals.reduce((s, m) => s + m.carbs, 0) * 10) / 10;
    const totalFats = Math.round(meals.reduce((s, m) => s + m.fats, 0) * 10) / 10;

    return {
      dayName: name,
      focus: `${dayThemes[idx]} • ${planFocus}`,
      totalCalories,
      totalProtein,
      totalCarbs,
      totalFats,
      meals,
    };
  });
}

