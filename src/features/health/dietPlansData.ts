// Recommendation Engine
export function recommendDietPlan(params: {
  locality?: string;
  weeklyLossKg?: number;
  age?: number;
  sex?: 'male' | 'female';
}): WeeklyDietPlan {
  const custom = getCustomDietPlans();
  const pool = [...PRESET_DIET_PLANS, ...custom];

  // Filter by locality first if chosen
  let filtered = pool;
  if (params.locality && params.locality !== 'all') {
    filtered = pool.filter(p => p.locality === params.locality);
    if (filtered.length === 0) filtered = pool;
  }

  // Filter or score by weeklyLossKg
  const targetLoss = params.weeklyLossKg || 0.5;
  const sorted = [...filtered].sort((a, b) => {
    const deltaA = Math.abs(a.weeklyLossKg - targetLoss);
    const deltaB = Math.abs(b.weeklyLossKg - targetLoss);
    return deltaA - deltaB;
  });

  return sorted[0] || PRESET_DIET_PLANS[0];
}
